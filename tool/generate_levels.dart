import 'dart:io';

import 'package:color_links/game/generator.dart';

void main() {
  final levels = PuzzleGenerator.buildAll();
  final buffer = StringBuffer()
    ..writeln('// Generated by tool/generate_levels.dart. Do not edit by hand.')
    ..writeln('const generatedSizes = <int>[');
  buffer.writeln('  ${levels.map((level) => level.size).join(', ')},');
  buffer
    ..writeln('];')
    ..writeln()
    ..writeln('const generatedFlows = <List<List<int>>>[');
  for (final level in levels) {
    buffer.writeln('  [');
    for (final flow in level.flows) {
      buffer.writeln('    $flow,');
    }
    buffer.writeln('  ],');
  }
  buffer.writeln('];');
  File('lib/game/level_data.dart').writeAsStringSync(buffer.toString());
  stdout.writeln('wrote ${levels.length} levels');
}
